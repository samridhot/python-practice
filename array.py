# Simple Python program with an array
numbers = [10, 20, 30, 40, 50]

# Print all elements
print("Array elements:", numbers)

# Access individual elements
print("First element:", numbers[0])
print("Last element:", numbers[-4])

# Loop through the array
print("Looping through array:")
for num in numbers:
    print(num)

print(numbers[4])
# Perform a simple operation (sum)
print("Sum of array:", sum(numbers))
